package com.example.ads.unity

/**
 * Centralized configuration for Unity Ads.
 *
 * Unity Monetization Dashboard Setup (https://cloud.unity.com or https://operate.dashboard.unity.com):
 * 1. Project / Game ID: Set below (800361482).
 * 2. Placement Type (IMPORTANT for standalone Unity Ads integration):
 *    - In the Unity Monetization dashboard under "Monetization > Ad Units / Placements":
 *      Ensure your placements are created as "Traditional (Waterfall)" placements, NOT "Header Bidding".
 *    - If a placement is set to "Header Bidding", Unity's servers expect an external mediation adMarkup
 *      auction payload and will log "Header bidding load invocation failed: adMarkup is missing".
 *    - Under "Project Settings > Mediation Partners", ensure it is set to "Unity Ads only" (or None)
 *      if you are not using an external mediation provider (such as AppLovin MAX or LevelPlay mediation).
 * 3. Placement IDs:
 *    - Standard Unity Android Banner: "Banner_Android"
 *    - Standard Unity Android Interstitial: "Interstitial_Android"
 *    - Standard Unity Android Rewarded: "Rewarded_Android"
 * 4. Test Mode: Set [IS_TEST_MODE] to false before releasing to Google Play production.
 */
object UnityAdsConfig {
    /**
     * Unity Game/Project ID provided for Android.
     */
    const val GAME_ID: String = "800361482"

    /**
     * Placement / Ad Unit IDs.
     * Default standard IDs generated by Unity Dashboard for Android projects:
     * - Banner: "Banner_Android"
     * - Interstitial: "Interstitial_Android"
     * - Rewarded: "Rewarded_Android"
     *
     * If your Unity Monetization Dashboard uses different Placement IDs, update them here:
     */
    const val BANNER_PLACEMENT_ID: String = "Banner_Android"
    const val INTERSTITIAL_PLACEMENT_ID: String = "Interstitial_Android"
    const val REWARDED_PLACEMENT_ID: String = "Rewarded_Android"

    /**
     * Toggle between Test Mode and Production Mode.
     * Uses BuildConfig.DEBUG automatically:
     * - true in debug/development builds.
     * - false in release/production builds (preventing test configuration from remaining active in production).
     */
    val IS_TEST_MODE: Boolean = com.example.BuildConfig.DEBUG

    /**
     * Master switch to enable or disable ads globally.
     */
    const val ADS_ENABLED: Boolean = true

    /**
     * Enable or disable specific ad formats.
     */
    const val BANNER_ADS_ENABLED: Boolean = true
    const val INTERSTITIAL_ADS_ENABLED: Boolean = true
    const val REWARDED_ADS_ENABLED: Boolean = true

    /**
     * Minimum interval (in milliseconds) between interstitial ads to protect user experience.
     * 60 seconds cooldown ensures ads are never shown back-to-back or excessively.
     */
    const val MIN_INTERSTITIAL_INTERVAL_MS: Long = 60_000L
}
